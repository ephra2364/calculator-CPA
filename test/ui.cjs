const { chromium, devices } = require('playwright');
const SH = process.env.SHOTS; const URL = 'http://localhost:8899/calculator-CPA/';
let pass = 0, fail = 0; const ok = (c, l) => { c ? pass++ : fail++; console.log((c ? '  ✔ ' : '  ✘ ') + l); };
(async () => {
  const b = await chromium.launch(); const errors = [];
  const ctx = await b.newContext({ ...devices['iPhone 8'], locale: 'fr-FR' });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  p.on('dialog', (d) => d.accept());
  const text = () => p.locator('main').innerText();
  await p.goto(URL); await p.waitForSelector('text=Pilote la rentabilité');
  await p.screenshot({ path: SH + '/01-accueil.png', fullPage: true });
  console.log('1. Exemples');
  await p.click('text=Charger des exemples');
  await p.waitForSelector('h1:has-text("Tableau de bord")');
  const t1 = await text();
  ok(/Produits suivis\s*3/.test(t1), 'tableau de bord : 3 produits');
  ok(/Produits déficitaires/.test(t1) && /Lampe solaire/.test(t1), 'classement présent');
  await p.screenshot({ path: SH + '/02-dashboard.png', fullPage: true });
  await p.click('text=Exemple — Ceinture de massage >> nth=0');
  await p.waitForSelector('text=Mes saisies');
  ok(/Mes chiffres/.test(await text()) && /Rentable|perds de l’argent/.test(await text()), 'écran simple : saisie + verdict');
  await p.screenshot({ path: SH + '/03a-simple-ceinture.png', fullPage: true });
  await p.click('text=Analyses détaillées');
  await p.waitForSelector('text=MON DIAGNOSTIC BUSINESS');
  ok(/En observation|Deadzone probable/.test(await text()), 'ceinture : dégradation détectée');
  await p.screenshot({ path: SH + '/03-diagnostic-ceinture.png', fullPage: true });
  for (const [tab, expect] of [['CPA Calculator', 'CPA BREAK-EVEN'], ['Profit Analyzer', 'Compte de résultat'], ['Livraison', 'De la commande à la livraison'], ['Marge', 'Où part ton prix'], ['Deadzone', 'Évolution des indicateurs'], ['Optimisation', 'COMMENT AMÉLIORER'], ['Scaling', 'Simulateur de scaling'], ['Résultats & historique', 'Résultats par période'], ['Produit & coûts', 'Informations générales']]) {
    await p.getByRole('button', { name: tab, exact: true }).click();
    const okk = await p.waitForSelector(`text=${expect}`, { timeout: 5000 }).then(() => true, () => false);
    ok(okk, `onglet ${tab}`);
    if (['Deadzone', 'Marge', 'Résultats & historique'].includes(tab)) await p.screenshot({ path: SH + `/04-${tab.replace(/\W+/g, '-')}.png`, fullPage: true });
  }
  await p.getByRole('button', { name: 'Deadzone', exact: true }).click();
  ok(/Fatigue publicitaire|Saturation d’audience/.test(await text()), 'cause de deadzone identifiée');

  console.log('2. Nouveau produit — écran simple');
  await p.click('text=+ NOUVEAU PRODUIT >> nth=0');
  await p.waitForSelector('text=Mon produit');
  const fill = async (label, v) => { await p.locator(`label:has-text("${label}") input`).first().fill(String(v)); };
  const T = async () => (await text()).replace(/[\u202f\u00a0]/g, ' ');
  await fill('Nom du produit', 'Montre test');
  await fill('Prix de vente', 15000); await fill('Prix de la pièce', 3000); await fill('Importation par pièce', 1000); await fill('Livraison par colis', 1500);
  ok(/avant la pub : 9 500 FCFA/.test(await T()), 'marge par pièce avant pub 9 500');
  await p.getByRole('button', { name: 'Valider', exact: true }).click();
  await fill('Dépenses pub Meta', 50000); await fill('Achats Meta', 30); await fill('Commandes Shopify', 25); await fill('Total livré', 20);
  const r = await T();
  ok(/Rentable — tu peux augmenter le budget/.test(r), 'verdict immédiat : scaler');
  ok(/Bénéfice de la journée\s*140 000 FCFA/.test(r), 'bénéfice de la journée 140 000');
  ok(/Bénéfice net par pièce\s*7 000 FCFA/.test(r) && /il te reste 7 000 FCFA après la pub/.test(r), 'bénéfice réel par pièce 7 000');
  ok(/Il te reste : 7 000 FCFA/.test(r) && /Pub :\s*2 500 FCFA/.test(r), 'décomposition d’une pièce');
  await p.click('text=Voir les indicateurs détaillés');
  const r2 = await T();
  ok(/CPA livré\)\s*2 500 FCFA/.test(r2) && /Pub maximale par pièce livrée\s*9 500 FCFA/.test(r2), 'CPA livré 2 500 / max 9 500');
  ok(/Taux de livraison\s*80 %/.test(r2) && /\+20 %/.test(r2), 'taux de livraison et écart Meta/Shopify');
  await p.screenshot({ path: SH + '/05-simple-saisie.png', fullPage: true });
  await p.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await p.waitForSelector('text=Mes saisies');
  ok(/Total : 140 000 FCFA/.test(await T()), 'saisie enregistrée');
  // deuxième saisie, la veille, pub trop chère
  const y = new Date(Date.now() - 86400000); const ys = `${y.getFullYear()}-${String(y.getMonth()+1).padStart(2,'0')}-${String(y.getDate()).padStart(2,'0')}`;
  await p.locator('label:has-text("Date") input').first().fill(ys);
  await fill('Dépenses pub Meta', 250000); await fill('Commandes Shopify', 25); await fill('Total livré', 20);
  ok(/Tu perds de l’argent/.test(await T()) && /12 500 FCFA par pièce livrée/.test(await T()), 'verdict : pas rentable (pub trop chère)');
  await p.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await p.waitForTimeout(300);
  ok(/Total : 80 000 FCFA/.test(await T()), 'total cumulé 80 000');
  ok(/Bénéfice estimé fin de mois/.test(await T()), 'estimation du mois affichée');
  await fill('Fixe ton objectif', 2000000);
  await p.getByRole('button', { name: 'Valider l’objectif', exact: true }).click();
  ok(/Pour atteindre 2 000 000 FCFA/.test(await T()) && /pièces livrées par jour/.test(await T()), 'plan pour atteindre l’objectif du mois');
  await p.reload(); await p.waitForTimeout(800);
  ok(/Montre test/.test(await text()) && /Total : 80 000/.test(await T()) && /Objectif du mois 2 000 000/.test(await T()), 'données conservées après rechargement');
  await p.screenshot({ path: SH + '/06-simple-historique.png', fullPage: true });

  const d = await b.newContext({ viewport: { width: 1280, height: 900 } }); const dp = await d.newPage();
  dp.on('pageerror', (e) => errors.push(e.message));
  await dp.goto(URL); await dp.click('text=Charger des exemples'); await dp.waitForSelector('text=Bénéfice par produit');
  await dp.screenshot({ path: SH + '/07-ordinateur.png', fullPage: true });
  ok(errors.length === 0, 'aucune erreur JavaScript' + (errors.length ? ': ' + errors.slice(0, 3).join(' | ') : ''));
  await b.close(); console.log(`\n${pass} réussis, ${fail} échoués`); process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
