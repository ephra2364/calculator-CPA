const { chromium, devices } = require('playwright');
const SH = process.env.SHOTS; const URL = 'http://localhost:8899/calculator-CPA/';
let pass = 0, fail = 0; const ok = (c, l) => { c ? pass++ : fail++; console.log((c ? '  ✔ ' : '  ✘ ') + l); };
(async () => {
  const b = await chromium.launch(); const errors = [];
  const ctx = await b.newContext({ ...devices['iPhone 8'], locale: 'fr-FR' });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  p.on('dialog', (d) => d.accept());
  const text = () => p.locator('main').innerText();
  await p.goto(URL); await p.waitForSelector('text=Pilote la rentabilité');
  await p.screenshot({ path: SH + '/01-accueil.png', fullPage: true });
  console.log('1. Exemples');
  await p.click('text=Charger des exemples');
  await p.waitForSelector('h1:has-text("Tableau de bord")');
  const t1 = await text();
  ok(/Produits suivis\s*3/.test(t1), 'tableau de bord : 3 produits');
  ok(/Produits déficitaires/.test(t1) && /Lampe solaire/.test(t1), 'classement présent');
  await p.screenshot({ path: SH + '/02-dashboard.png', fullPage: true });
  await p.click('text=Exemple — Ceinture de massage >> nth=0');
  await p.waitForSelector('text=MON DIAGNOSTIC BUSINESS');
  ok(/En observation|Deadzone probable/.test(await text()), 'ceinture : dégradation détectée');
  await p.screenshot({ path: SH + '/03-diagnostic-ceinture.png', fullPage: true });
  for (const [tab, expect] of [['CPA Calculator', 'CPA BREAK-EVEN'], ['Profit Analyzer', 'Compte de résultat'], ['Livraison', 'De la commande à la livraison'], ['Marge', 'Où part ton prix'], ['Deadzone', 'Évolution des indicateurs'], ['Optimisation', 'COMMENT AMÉLIORER'], ['Scaling', 'Simulateur de scaling'], ['Résultats & historique', 'Résultats par période'], ['Produit & coûts', 'Informations générales']]) {
    await p.getByRole('button', { name: tab, exact: true }).click();
    const okk = await p.waitForSelector(`text=${expect}`, { timeout: 5000 }).then(() => true, () => false);
    ok(okk, `onglet ${tab}`);
    if (['Deadzone', 'Marge', 'Résultats & historique'].includes(tab)) await p.screenshot({ path: SH + `/04-${tab.replace(/\W+/g, '-')}.png`, fullPage: true });
  }
  await p.getByRole('button', { name: 'Deadzone', exact: true }).click();
  ok(/Fatigue publicitaire|Saturation d’audience/.test(await text()), 'cause de deadzone identifiée');

  console.log('2. Nouveau produit (CAS 1)');
  await p.click('text=+ NOUVEAU PRODUIT >> nth=0');
  await p.waitForSelector('text=Informations générales');
  const fill = async (label, v) => { await p.locator(`label:has-text("${label}") input`).first().fill(String(v)); };
  await p.locator('label:has-text("Nom du produit") input').fill('Montre test');
  await fill('Prix de vente', 15000);
  await fill('Prix d’achat fournisseur', 3000000); await fill('Transport international', 500000); await fill('Douane', 300000); await fill('Transit', 200000); await fill('Quantité importée', 1000);
  ok(/Coût complet par unité\s*4\s000 FCFA/.test((await text()).replace(/ /g, ' ')), 'coût unitaire calculé : 4 000 FCFA');
  await fill('Confirmation / closing', 500); await fill('Livraison réussie', 1500); await fill('Livraison échouée', 1000);
  await fill('CPA cible souhaité', 3000);
  await p.click('text=Étape suivante');
  await p.click('text=+ Saisir ma première période');
  await p.locator('label:has-text("Date de début") input').fill('2026-10-01');
  await p.locator('label:has-text("Date de fin") input').fill('2026-10-07');
  await fill('Dépenses publicitaires', 200000);
  await fill('Reçues', 100); await fill('Confirmées', 80); await fill('Expédiées', 80); await fill('Livrées', 64); await fill('Refusées', 16);
  await p.click('text=Enregistrer la période');
  await p.waitForSelector('text=Résultats par période');
  await p.getByRole('button', { name: 'CPA Calculator', exact: true }).click();
  const c1 = (await text()).replace(/[  ]/g, ' ');
  ok(/CPA par commande\s*2 000 FCFA/.test(c1), 'CPA 2 000');
  ok(/CPA par livraison réussie\s*3 125 FCFA/.test(c1), 'CPA livré 3 125');
  ok(/Par commande reçue\s*5 520 FCFA/.test(c1), 'CPA break-even 5 520');
  ok(/CPA INFÉRIEUR À L’OBJECTIF de 1 000 FCFA/.test(c1), 'écart vs objectif');
  await p.screenshot({ path: SH + '/05-cpa.png', fullPage: true });
  await p.getByRole('button', { name: 'Profit Analyzer', exact: true }).click();
  ok(/352 000 FCFA/.test((await text()).replace(/[  ]/g, ' ')), 'bénéfice 352 000');
  await p.getByRole('button', { name: 'Optimisation', exact: true }).click();
  await p.getByRole('button', { name: 'CPA −10 %', exact: true }).click();
  ok(/\+20 000 FCFA/.test((await text()).replace(/[  ]/g, ' ')), 'simulation CPA −10 % → +20 000');
  await p.screenshot({ path: SH + '/06-optimisation.png', fullPage: true });
  await p.reload(); await p.waitForTimeout(800);
  ok(/Montre test/.test(await text()), 'données conservées après rechargement');

  const d = await b.newContext({ viewport: { width: 1280, height: 900 } }); const dp = await d.newPage();
  dp.on('pageerror', (e) => errors.push(e.message));
  await dp.goto(URL); await dp.click('text=Charger des exemples'); await dp.waitForSelector('text=Bénéfice par produit');
  await dp.screenshot({ path: SH + '/07-ordinateur.png', fullPage: true });
  ok(errors.length === 0, 'aucune erreur JavaScript' + (errors.length ? ': ' + errors.slice(0, 3).join(' | ') : ''));
  await b.close(); console.log(`\n${pass} réussis, ${fail} échoués`); process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
